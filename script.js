let currentLanguage = localStorage.getItem("medipath-language") || "pt";

function t(key) {
  return translations[currentLanguage][key] || translations.pt[key] || key;
}

function setLanguage(language) {
  currentLanguage = translations[language] ? language : "pt";
  document.documentElement.lang = currentLanguage === "pt" ? "pt-BR" : "en";

  document.querySelectorAll("[data-i18n]").forEach((element) => {
    element.textContent = t(element.dataset.i18n);
  });

  document.querySelectorAll("[data-i18n-aria]").forEach((element) => {
    element.setAttribute("aria-label", t(element.dataset.i18nAria));
  });

  languageButtons.forEach((button) => {
    const active = button.dataset.lang === currentLanguage;
    button.classList.toggle("active", active);
    button.setAttribute("aria-pressed", active ? "true" : "false");
  });

  applyContactConfig();
  validateWhatsAppInput();
  localStorage.setItem("medipath-language", currentLanguage);
}

function getContactText(group, fallbackKey) {
  return group?.[currentLanguage] || group?.pt || t(fallbackKey);
}

function buildWhatsAppUrl(message = "") {
  const baseUrl = contact.whatsappUrl || "#";
  if (!message) return baseUrl;
  return `${baseUrl}?text=${encodeURIComponent(message)}`;
}

function applyContactConfig() {
  whatsappLinks.forEach((link) => {
    link.href = buildWhatsAppUrl();
    link.target = "_blank";
    link.rel = "noopener noreferrer";
  });

  contactButtons.forEach((element) => {
    element.textContent = getContactText(contact.buttonText, "footer.contact");
  });

  contactHelpers.forEach((element) => {
    element.textContent = getContactText(contact.helperText, "form.note");
  });
}

function setNote(message, type = "neutral") {
  if (!note) return;
  note.textContent = message;
  note.dataset.state = type;
}

function getBrazilianMobileDigits(value = "") {
  let digits = value.replace(/\D/g, "");
  if (digits.startsWith("55") && digits.length > 11) digits = digits.slice(2);
  return digits.slice(0, 11);
}

function formatBrazilianMobile(value = "") {
  const digits = getBrazilianMobileDigits(value);
  if (!digits) return "";
  if (digits.length <= 2) return `(${digits}`;
  if (digits.length <= 7) return `(${digits.slice(0, 2)}) ${digits.slice(2)}`;
  return `(${digits.slice(0, 2)}) ${digits.slice(2, 7)}-${digits.slice(7)}`;
}

function isValidBrazilianMobile(value = "") {
  return /^[1-9]\d9\d{8}$/.test(getBrazilianMobileDigits(value));
}

function validateWhatsAppInput() {
  if (!whatsappInput) return true;
  const valid = !whatsappInput.value || isValidBrazilianMobile(whatsappInput.value);
  whatsappInput.setCustomValidity(valid ? "" : t("form.whatsappError"));
  return valid;
}

function getFormFields() {
  const data = new FormData(form);
  return {
    full_name: data.get("full_name")?.toString().trim() || "",
    email: data.get("email")?.toString().trim() || "",
    city: data.get("city")?.toString().trim() || "",
    state: data.get("state")?.toString().trim() || "",
    specialty: data.get("specialty")?.toString().trim() || null,
    whatsapp: data.get("whatsapp")
      ? `55${getBrazilianMobileDigits(data.get("whatsapp").toString())}`
      : null,
    launch_consent: data.get("launch_consent") === "on",
  };
}

async function submitToSupabase(fields) {
  if (!config.supabaseUrl || !config.publishableKey) {
    throw new Error("Missing Supabase public configuration");
  }

  const response = await fetch(`${config.supabaseUrl}/rest/v1/waitlist_signups`, {
    method: "POST",
    headers: {
      apikey: config.publishableKey,
      authorization: `Bearer ${config.publishableKey}`,
      "content-type": "application/json",
      prefer: "return=minimal",
    },
    body: JSON.stringify(fields),
  });

  if (!response.ok) {
    throw new Error(`Waitlist submission failed with ${response.status}`);
  }

  return true;
}

function showConfirmation() {
  form.hidden = true;
  confirmation.hidden = false;
  confirmation.focus?.();
}

