const form = document.querySelector("#access-form");
const note = document.querySelector("#form-note");
const languageButtons = document.querySelectorAll("[data-lang]");
let currentLanguage = localStorage.getItem("medipath-language") || "pt";

function t(key) {
  return translations[currentLanguage][key] || translations.pt[key] || key;
}

function setLanguage(language) {
  currentLanguage = translations[language] ? language : "pt";
  document.documentElement.lang = currentLanguage === "pt" ? "pt-BR" : "en";

  document.querySelectorAll("[data-i18n]").forEach((element) => {
    element.textContent = t(element.dataset.i18n);
  });

  if (note) {
    note.textContent = t("form.note");
  }

  languageButtons.forEach((button) => {
    const active = button.dataset.lang === currentLanguage;
    button.classList.toggle("active", active);
    button.setAttribute("aria-pressed", active ? "true" : "false");
  });

  localStorage.setItem("medipath-language", currentLanguage);
}

languageButtons.forEach((button) => {
  button.addEventListener("click", () => setLanguage(button.dataset.lang));
});

form?.addEventListener("submit", (event) => {
  event.preventDefault();

  const data = new FormData(form);
  const fields = {
    nome: data.get("nome")?.toString().trim() || "",
    email: data.get("email")?.toString().trim() || "",
    especialidade: data.get("especialidade")?.toString().trim() || "",
    clinica: data.get("clinica")?.toString().trim() || "",
    whatsapp: data.get("whatsapp")?.toString().trim() || "",
    mensagem: data.get("mensagem")?.toString().trim() || "",
  };

  const body = [
    t("email.greeting"),
    "",
    `${t("form.name")}: ${fields.nome}`,
    `${t("form.email")}: ${fields.email}`,
    `${t("form.specialty")}: ${fields.especialidade || t("email.notProvided")}`,
    `${t("form.clinic")}: ${fields.clinica || t("email.notProvided")}`,
    `${t("form.whatsapp")}: ${fields.whatsapp || t("email.notProvided")}`,
    "",
    `${t("form.message")}: ${fields.mensagem || t("email.notProvided")}`,
  ].join("\n");

  const subject = encodeURIComponent(t("email.subject"));
  const encodedBody = encodeURIComponent(body);
  window.location.href = `mailto:contato@medipath.ai?subject=${subject}&body=${encodedBody}`;

  if (note) {
    note.textContent = t("form.opening");
  }
});

setLanguage(currentLanguage);
